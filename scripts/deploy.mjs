// Deploy the basket factory and a demo basket, then write the frontend env file.
//
//   node scripts/deploy.mjs local
//   node scripts/deploy.mjs testnet
//   node scripts/deploy.mjs mainnet
//
// Or from the repo root: pnpm run deploy:local
//
// Environment (a root .env file is loaded when the variable is not already set):
//   PRIVATE_KEY   deployer key, required for testnet and mainnet
//   RPC_URL       override the default RPC for the chosen target
//   VERIFY        set to 0 to skip Blockscout verification
//
// scripts/deploy.sh is the same flow for bash, and the learn page quotes it.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { combined, must, run } from "./run.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const envFile = resolve(root, "apps/frontend/.env.local");

// Anvil's account zero. Public test key. Never use this pattern on a live network.
const ANVIL_KEY = "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80";

const TARGETS = {
  local: {
    chainId: 31337,
    rpc: "http://localhost:8545",
    verifierUrl: "",
    defaultKey: ANVIL_KEY,
  },
  testnet: {
    chainId: 46630,
    rpc: "https://rpc.testnet.chain.robinhood.com",
    verifierUrl: "https://explorer.testnet.chain.robinhood.com/api/",
    defaultKey: "",
  },
  mainnet: {
    chainId: 4663,
    rpc: "https://rpc.mainnet.chain.robinhood.com",
    verifierUrl: "https://robinhoodchain.blockscout.com/api/",
    defaultKey: "",
  },
};

loadDotEnv(resolve(root, ".env"));

const targetName = process.argv[2] ?? "local";
if (targetName === "-h" || targetName === "--help") {
  console.log("Usage: node scripts/deploy.mjs <local|testnet|mainnet>");
  process.exit(0);
}

const target = TARGETS[targetName];
if (!target) {
  console.error(`unknown target: ${targetName} (expected local, testnet, or mainnet)`);
  process.exit(1);
}

const rpc = process.env.RPC_URL || target.rpc;
const privateKey = process.env.PRIVATE_KEY || target.defaultKey;
if (!privateKey) {
  console.error(`PRIVATE_KEY is required for ${targetName} deploys`);
  process.exit(1);
}

const chain = must("cast", ["chain-id", "--rpc-url", rpc]);
const actualChainId = chain.stdout.trim().split(/\s+/)[0];
if (actualChainId !== String(target.chainId)) {
  console.error(`rpc ${rpc} reports chain id ${actualChainId}, expected ${target.chainId}`);
  process.exit(1);
}

console.error(`deploying to ${targetName} (chain id ${target.chainId}) via ${rpc}`);

// Orbit gas estimates include an L1 data fee that can move between estimation
// and inclusion. The multiplier leaves headroom. --slow waits for each receipt
// so a later transaction never races an earlier deployment.
const args = [
  "script",
  "script/Deploy.s.sol:Deploy",
  "--rpc-url",
  rpc,
  "--private-key",
  privateKey,
  "--broadcast",
  "--slow",
  "--gas-estimate-multiplier",
  "300",
];

if (target.verifierUrl && process.env.VERIFY !== "0") {
  args.push("--verify", "--verifier", "blockscout", "--verifier-url", target.verifierUrl);
}

const deployed = run("forge", args, { cwd: resolve(root, "contracts") });
const output = combined(deployed);
process.stderr.write(output);
if (deployed.status !== 0) process.exit(deployed.status);

const factory = grab(output, "FACTORY");
const basket = grab(output, "DEMO_BASKET");
if (!factory || !basket) {
  console.error("could not parse deployed addresses from forge output");
  process.exit(1);
}

mkdirSync(dirname(envFile), { recursive: true });
const lines = [
  `# auto-generated by scripts/deploy.mjs (${targetName})`,
  `NEXT_PUBLIC_CHAIN_ID=${target.chainId}`,
  `NEXT_PUBLIC_FACTORY_ADDRESS=${factory}`,
  `NEXT_PUBLIC_DEMO_BASKET_ADDRESS=${basket}`,
  `NEXT_PUBLIC_RPC_URL=${targetName === "local" ? "http://localhost:8545" : rpc}`,
  "",
];
writeFileSync(envFile, lines.join("\n"));

console.error("");
console.error(`factory:     ${factory}`);
console.error(`demo basket: ${basket}`);
console.error(`wrote ${envFile}`);
console.error("restart the frontend if it is already running so Next.js reloads these addresses");

function grab(text, key) {
  const match = text.match(new RegExp(`${key}=0x[0-9a-fA-F]{40}`));
  return match ? match[0].slice(key.length + 1) : "";
}

function loadDotEnv(path) {
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}
